import type { MetadataRoute } from 'next';

export default function robots(): MetadataRoute.Robots {
  const baseUrl = process.env.NEXT_PUBLIC_APP_URL || 'https://autotrader.trade';

  return {
    rules: [
      {
        userAgent: '*',
        allow: [
          '/',
          '/features',
          '/brokers',
          '/pricing',
          '/how-it-works',
          '/faqs',
          '/about',
          '/contact',
          '/education',
          '/terms',
          '/privacy',
          '/risk-disclosure',
          '/refund-policy',
        ],
        disallow: [
          '/api/',
          '/dashboard',
          '/dashboard/*',
          '/live-trading',
          '/live-trading/*',
          '/trading',
          '/trading/*',
          '/app/',
          '/app/*',
          '/broker',
          '/broker/*',
          '/strategies',
          '/strategies/*',
          '/trades',
          '/trades/*',
          '/analytics',
          '/analytics/*',
          '/funds',
          '/funds/*',
          '/risk',
          '/risk/*',
          '/notifications',
          '/notifications/*',
          '/system',
          '/system/*',
          '/settings',
          '/settings/*',
          '/admin',
          '/admin/*',
          '/onboarding',
          '/onboarding/*',
          '/auth/',
          '/auth/*',
          '/login',
          '/signup',
          '/forgot-password',
          '/reset-password',
        ],
      },
    ],
    sitemap: `${baseUrl}/sitemap.xml`,
    host: baseUrl,
  };
}
